import CoreGraphics
import Foundation

/// The overlay's "Explain copied text ⏎" chip (LN §3 T3/T4): offered only when the general
/// pasteboard changed since the last Explain (or since PaperDeck's own copy) and holds text or an
/// image (⌘C in any app, or ⌃⇧⌘4 to the clipboard). Only `changeCount` and the type names are looked
/// at to offer it — never the contents, which are read when the user presses Return (macOS 15.4+
/// pasteboard privacy: reading is what may ask; looking at types doesn't). Password managers' marked
/// items are never offered. Pure; owned by the Explain UI lane (A2).
package struct ClipboardOffer: Sendable, Equatable {
    package enum Content: String, Sendable, Equatable { case text, image }

    package var content: Content
    /// The pasteboard's `changeCount` when offered (Return reads only if it is still this one).
    package var changeCount: Int

    package init(content: Content, changeCount: Int) {
        self.content = content; self.changeCount = changeCount
    }

    /// Marker types of concealed / transient items (nspasteboard.org): never offered or read.
    package static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]
    package static let textTypes: Set<String> = ["public.utf8-plain-text", "public.plain-text", "NSStringPboardType",
                                                 "public.utf16-plain-text", "public.rtf"]
    package static let imageTypes: Set<String> = ["public.png", "public.tiff", "public.jpeg", "public.heic",
                                                  "NeXT TIFF v4.0 pasteboard type", "Apple PNG pasteboard type"]

    /// The offer for a pasteboard with `types` at `changeCount`; nil when it is unchanged since
    /// `lastConsumed`, concealed, or holds neither text nor an image. Text wins over an image (a
    /// rich copy carries both; the text is what was selected).
    package static func make(changeCount: Int, lastConsumed: Int?, types: [String]) -> ClipboardOffer? {
        guard changeCount != lastConsumed else { return nil }
        let set = Set(types)
        guard set.isDisjoint(with: concealedTypes) else { return nil }
        if !set.isDisjoint(with: textTypes) { return ClipboardOffer(content: .text, changeCount: changeCount) }
        if !set.isDisjoint(with: imageTypes) { return ClipboardOffer(content: .image, changeCount: changeCount) }
        return nil
    }

    /// Copied text as Explain takes it: soft line breaks of a PDF selection joined ("analy-\nsis" →
    /// "analysis" when the next line goes on in lowercase; a CJK line break dropped), runs of spaces
    /// collapsed, paragraphs kept, trimmed, at most `ExplanationRecord.maxExcerpt` characters.
    /// nil when nothing is left.
    package static func normalize(_ raw: String, limit: Int = ExplanationRecord.maxExcerpt) -> String? {
        let text = raw.replacingOccurrences(of: "\r\n", with: "\n").replacingOccurrences(of: "\r", with: "\n")
        let paragraphs = text.components(separatedBy: "\n\n").map { para -> String in
            var out = ""
            let lines = para.components(separatedBy: "\n").map { $0.trimmingCharacters(in: .whitespaces) }.filter { !$0.isEmpty }
            for line in lines {
                guard let lastOut = out.last else { out = line; continue }
                let first = line.first!
                if lastOut == "-", first.isLowercase, out.count >= 2, out[out.index(out.endIndex, offsetBy: -2)].isLetter {
                    // "analy-" + "sis" → "analysis"; a compound already hyphenated ("state-of-the-" +
                    // "art") keeps its hyphen.
                    let word = out.dropLast().reversed().prefix { !$0.isWhitespace }
                    if !word.contains("-") { out.removeLast() }
                    out += line
                } else if isCJK(lastOut) || isCJK(first) {
                    out += line                                        // CJK lines join without a space
                } else {
                    out += " " + line
                }
            }
            return out.replacingOccurrences(of: "\u{00A0}", with: " ")
                .replacingOccurrences(of: #"[ \t]{2,}"#, with: " ", options: .regularExpression)
        }.filter { !$0.isEmpty }
        let joined = paragraphs.joined(separator: "\n\n").trimmingCharacters(in: .whitespacesAndNewlines)
        guard !joined.isEmpty else { return nil }
        return String(joined.prefix(limit))
    }

    /// One line of at most `limit` characters (the panel's quote line).
    package static func preview(_ text: String, limit: Int = 80) -> String {
        let flat = text.split(whereSeparator: { $0.isWhitespace || $0.isNewline }).joined(separator: " ")
        return flat.count > limit ? String(flat.prefix(limit - 1)) + "…" : flat
    }

    private static func isCJK(_ c: Character) -> Bool {
        c.unicodeScalars.contains { (0x3000...0x9FFF).contains($0.value) || (0xF900...0xFAFF).contains($0.value)
            || (0xFF00...0xFFEF).contains($0.value) || (0xAC00...0xD7AF).contains($0.value) }
    }
}
